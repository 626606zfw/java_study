package day3;

// if语句的基本使用
public class Demo02If {
	public static void main(String[] args) {
		System.out.println("今天天气很好，小明走在路上，突然看到一个钱包在地上，他捡起来");
		int age = 19;
		if (age >= 18) {
			System.out.println("小明已经成年了，开始high起来");
			System.out.println("他约了一群朋友，开始聚餐");
			System.out.println("酒足饭饱后，大家唱歌跳舞");
		}
		System.out.println("回家吃晚饭");
	}
}
